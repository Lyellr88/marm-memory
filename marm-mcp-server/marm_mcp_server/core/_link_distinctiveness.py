_NUMERIC = re.compile(r"^[vV]?[\d.\-_+→>]+$")
_CODE_SHAPED = re.compile(r"[_.]|::|[a-z][A-Z]|^[A-Z][a-z]+[A-Z]")


def is_linkable(name: str) -> bool:
    """True when `name` could plausibly be a reference to a specific symbol."""
    if not isinstance(name, str):
        return False
    text = name.strip()
    if not text or len(text) < 3:
        return False
    # A symbol reference is one token. "11 Open PRs" and "48 Cargo.toml Files
    # Across Project Structure" are sentence fragments the extractor kept whole.
    if any(ch.isspace() for ch in text):
        return False
    # Bare numbers and version strings: "0.15", "11", "2.0", "0.5→0.8", "v1.8.2".
    if _NUMERIC.match(text):
        return False
    # An identifier shape is positive evidence, and outranks the stoplist:
    # `update_state` and `UpdateState` are specific where `update` is not.
    # Note this also admits `_update` and `__update__`, since `_CODE_SHAPED`
    # matches a bare underscore. That is intended -- a leading underscore is a
    # private-symbol convention, so the name really is an identifier -- but it
    # means nothing containing `_` ever reaches the stoplist below.
    if _CODE_SHAPED.search(text):
        return True
    return text.casefold() not in _COMMON


# A memory is rarely "about" a heading in a README or a directory. These kinds
# are structural artefacts the indexer records, not symbols a memory refers to,
# and matching them produced Changelog -> README.md and popup -> a folder.
NON_SYMBOL_LABELS = {"section", "folder", "file", "project", "branch", "module"}


def is_symbol_label(label: object) -> bool:
    """True when a matched node is a real code symbol rather than structure."""
    if not isinstance(label, str) or not label.strip():
        return True  # unlabelled: let the name gate decide
    return label.strip().casefold() not in NON_SYMBOL_LABELS
