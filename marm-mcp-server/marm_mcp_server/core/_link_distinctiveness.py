"""Distinctiveness gate for memory->code symbol linking.

MARM links a concept entity to a code symbol when the entity's name matches a
symbol name exactly (`link_method: exact_symbol`, confidence 1.0). Exactness is
not the same as aboutness: in a repository with tens of thousands of symbols,
ordinary English words match something almost every time.

Observed on a 31,452-node repo, every one of the six links produced was a
coincidence of this kind:

    upload    -> a Swift method          actions  -> the .github/actions folder
    update    -> a Kotlin method         updates  -> a var in dependabot.yml
    toml      -> a var in Cargo.toml     criterion-> a var in Cargo.toml

None of those memories were about those symbols. A wrong link is worse than no
link, because it is presented at confidence 1.0 next to the code it names.

The gate answers one question: could this name plausibly be a reference to a
specific symbol? A name earns a link if it LOOKS like an identifier, or if it is
at least not an everyday word.
"""

